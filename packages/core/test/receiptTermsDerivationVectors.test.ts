import { readFileSync } from "node:fs";

import { describe, expect, test } from "vitest";

import {
  TermsUpdateRefusedError,
  decodeTermsUpdate,
  encodeTermsUpdate,
  termsUpdatePartnership,
} from "../src/config/termsUpdate";
import type { CommittedPayload } from "../src/records/exchangeRecord";
import { buildReceiptContent } from "../src/records/signedReceipt";
import { fromBase64Url, toBase64Url } from "../src/utils/crypto";

interface PayloadSide {
  payload: CommittedPayload;
  canonicalJson: string;
  canonicalHex: string;
  macHex: string;
}

interface Vectors {
  receiptPayloadMacs: {
    label: string;
    sessionKeyHex: string;
    cases: {
      name: string;
      initiatorToResponder: PayloadSide;
      responderToInitiator: PayloadSide;
    }[];
  };
  termsUpdate: {
    labelPrefix: string;
    sharedSecretHex: string;
    partnershipHex: string;
    bodyText: string;
    bodyHex: string;
    macHex: string;
  };
}

// Generated by vectors/generate-receipt-terms-derivation-vectors.mjs from fixed
// inputs with node:crypto and none of this package's code, so a derivation
// change here fails against bytes it did not produce.
const vectors: Vectors = JSON.parse(
  readFileSync(
    new URL("./vectors/receipt-terms-derivation-vectors.json", import.meta.url),
    "utf8",
  ),
);

const bytes = (hex: string): Uint8Array<ArrayBuffer> =>
  Uint8Array.from(Buffer.from(hex, "hex"));
const base64Url = (hex: string): string => toBase64Url(bytes(hex));

describe("receipt payload MACs against independent known answers", () => {
  const { sessionKeyHex, cases } = vectors.receiptPayloadMacs;

  test.each(cases)(
    "$name: both parties place each direction's MAC as the vector states",
    async (c) => {
      const expected = {
        termsHash: "dGVybXNIYXNo",
        initiatorToResponderPayload: base64Url(c.initiatorToResponder.macHex),
        responderToInitiatorPayload: base64Url(c.responderToInitiator.macHex),
        binder: "YmluZGVy",
      };
      for (const role of ["initiator", "responder"] as const) {
        const [sent, received] =
          role === "initiator"
            ? [c.initiatorToResponder, c.responderToInitiator]
            : [c.responderToInitiator, c.initiatorToResponder];
        expect(
          await buildReceiptContent(
            role,
            expected.termsHash,
            sent.payload,
            received.payload,
            expected.binder,
            bytes(sessionKeyHex),
          ),
        ).toEqual(expected);
      }
    },
  );

  test("the vector's canonical text is the payload it MACs", () => {
    for (const c of cases)
      for (const side of [c.initiatorToResponder, c.responderToInitiator]) {
        expect(JSON.stringify(side.payload)).toBe(side.canonicalJson);
        expect(Buffer.from(side.canonicalJson, "utf8").toString("hex")).toBe(
          side.canonicalHex,
        );
      }
  });

  test("the two directions give different MACs for the same payload", async () => {
    const [first] = cases;
    const payload = (first as (typeof cases)[number]).initiatorToResponder
      .payload;
    const content = await buildReceiptContent(
      "initiator",
      "dGVybXNIYXNo",
      payload,
      payload,
      "YmluZGVy",
      bytes(sessionKeyHex),
    );
    expect(content.initiatorToResponderPayload).not.toBe(
      content.responderToInitiatorPayload,
    );
  });
});

describe("terms update derivations against independent known answers", () => {
  const terms = vectors.termsUpdate;
  const secret = base64Url(terms.sharedSecretHex);
  const goodMac = base64Url(terms.macHex);
  const signedBody = toBase64Url(bytes(terms.bodyHex));

  test("the vector's body text is the bytes its MAC covers", () => {
    expect(Buffer.from(terms.bodyText, "utf8").toString("hex")).toBe(
      terms.bodyHex,
    );
  });

  test("the partnership identifier is the vector's", async () => {
    expect(await termsUpdatePartnership(secret)).toBe(
      base64Url(terms.partnershipHex),
    );
  });

  test("an update made under the secret states the vector's partnership", async () => {
    const { linkageTerms } = JSON.parse(terms.bodyText) as {
      linkageTerms: never;
    };
    const encoded = await encodeTermsUpdate({ linkageTerms }, secret);
    const body = JSON.parse(
      new TextDecoder().decode(fromBase64Url(encoded.split(".")[0] as string)),
    ) as { partnership: string };
    expect(body.partnership).toBe(base64Url(terms.partnershipHex));
  });

  test("an update carrying the vector's MAC over the vector's body is accepted", async () => {
    const decoded = await decodeTermsUpdate(`${signedBody}.${goodMac}`, secret);
    expect(decoded).toEqual({
      linkageTerms: (JSON.parse(terms.bodyText) as { linkageTerms: unknown })
        .linkageTerms,
    });
  });

  test("the MAC of the encoded body is the vector's MAC", async () => {
    const { linkageTerms } = JSON.parse(terms.bodyText) as {
      linkageTerms: never;
    };
    const encoded = await encodeTermsUpdate({ linkageTerms }, secret);
    expect(encoded).toBe(`${signedBody}.${goodMac}`);
  });

  test("a MAC that differs from the vector's in one byte is refused", async () => {
    const wrong = bytes(terms.macHex);
    wrong[0] = (wrong[0] as number) ^ 1;
    const refusal = await decodeTermsUpdate(
      `${signedBody}.${toBase64Url(wrong)}`,
      secret,
    ).catch((err: unknown) => err);
    expect(refusal).toBeInstanceOf(TermsUpdateRefusedError);
    expect((refusal as TermsUpdateRefusedError).check).toBe("authentication");
  });
});
