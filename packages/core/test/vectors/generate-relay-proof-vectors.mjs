// Independent generator for test/vectors/relay-proof-vectors.json.
//
// Reimplements the WebSocket relay proof (docs/spec/PROTOCOL.md, "The
// WebSocket relay proof") with Node's OpenSSL-backed `crypto` (hkdfSync,
// createHmac) -- a different code path from the module under test, which uses
// WebCrypto. websocketRelayProof.test.ts asserts the module reproduces these
// vectors.
//
// It first re-derives two values computed by OpenSSL's command line and pinned
// elsewhere: the relay key of the secret 0x00..0x1f (relayCredential.test.ts)
// and the registrar proof key of that relay key (PROTOCOL.md, "The registrar
// request proof"), so the chain this file starts from is anchored outside it.
//
// Run:  node packages/core/test/vectors/generate-relay-proof-vectors.mjs
// It prints the JSON to stdout; redirect into relay-proof-vectors.json to
// refresh, then run `npm run format`.

import { createHmac, hkdfSync } from "node:crypto";

const RELAY_KEY_INFO = "alcove-relay-key-v2";
const REGISTRAR_PROOF_KEY_INFO = "alcove-relay-registrar-v2:proof-key";
const PROOF_KEY_INFO = "alcove-relay-websocket-v2:proof-key";
const PROOF_MESSAGE_LABEL = "alcove-relay-websocket-v2:hello";
const ROLES = ["inviter", "acceptor"];

// Computed by `openssl kdf ... HKDF`, outside this file and the module.
const ANCHOR_RELAY_KEY =
  "1d970dcfd9f445a4c83c4ee3b03845209f891b2931e8b7bb2b41a17dd2249a9e";
const ANCHOR_REGISTRAR_PROOF_KEY =
  "4044b292b68d07e7d1dcbc69635477d8bfbc8839bad3232949526928bf8551a2";

const hex = (b) => Buffer.from(b).toString("hex");
// HKDF-SHA-256 with a 32-byte zero salt, as utils/crypto.ts hkdfDerive.
const hkdf = (ikm, info, len) =>
  Buffer.from(
    hkdfSync("sha256", ikm, Buffer.alloc(32), Buffer.from(info, "utf8"), len),
  );
const hmac = (key, data) => createHmac("sha256", key).update(data).digest();

const secret = Buffer.from(Array.from({ length: 32 }, (_, i) => i));
const relayKeyHex = hex(hkdf(secret, RELAY_KEY_INFO, 32));
if (relayKeyHex !== ANCHOR_RELAY_KEY) {
  throw new Error("relay key anchor self-check failed");
}
const relayKeyBytes = Buffer.from(relayKeyHex, "hex");
const registrarProofKey = hkdf(relayKeyBytes, REGISTRAR_PROOF_KEY_INFO, 32);
if (hex(registrarProofKey) !== ANCHOR_REGISTRAR_PROOF_KEY) {
  throw new Error("registrar proof key anchor self-check failed");
}
const proofKey = hkdf(relayKeyBytes, PROOF_KEY_INFO, 32);

const madeAtSeconds = 1767225600;
const ttlSeconds = 300;
const expiresAtSeconds = madeAtSeconds + ttlSeconds;

const proofs = ROLES.map((role) => {
  const message = [PROOF_MESSAGE_LABEL, role, String(expiresAtSeconds)].join(
    "\n",
  );
  return {
    role,
    message,
    messageHex: hex(Buffer.from(message, "ascii")),
    tagHex: hex(hmac(proofKey, Buffer.from(message, "ascii"))),
  };
});

const vector = {
  description:
    "Known-answer vectors for the WebSocket relay proof " +
    '(docs/spec/PROTOCOL.md, "The WebSocket relay proof"): ' +
    "the relay key of the shared secret 0x00..0x1f, the proof key derived from it, the registrar proof key of the " +
    "same relay key for comparison, and a proof for each rendezvous role at " +
    "one expiry. Generated by generate-relay-proof-vectors.mjs with Node's " +
    "crypto; packages/core/src/websocketRelayProof.ts reproduces them, held " +
    "by websocketRelayProof.test.ts.",
  construction: {
    proofKey:
      'HKDF-SHA-256(ikm = unhex(relay_key), salt = 0x00 * 32, info = "' +
      PROOF_KEY_INFO +
      '", 32)',
    message: `"${PROOF_MESSAGE_LABEL}" LF role LF decimal(expiry)`,
    tag: "HMAC-SHA-256(key = proof_key, msg = ascii(message))",
  },
  inputs: {
    sharedSecret: secret.toString("base64url"),
    madeAtSeconds,
    ttlSeconds,
    expiresAtSeconds,
  },
  derived: {
    relayKeyHex,
    proofKeyHex: hex(proofKey),
    registrarProofKeyHex: hex(registrarProofKey),
  },
  proofs,
};

process.stdout.write(`${JSON.stringify(vector, null, 2)}\n`);
